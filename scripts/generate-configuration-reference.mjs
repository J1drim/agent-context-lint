import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { format, resolveConfig } from "prettier";

import {
  CONFIGURATION_SOURCE_LIMITS,
  CONFIGURATION_VALUE_LIMITS,
} from "../packages/core/src/configuration-contracts.ts";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const schemaPath = path.join(
  root,
  "packages/core/schemas/agent-context-lint-config.v1.schema.json",
);
const outputPath = path.join(root, "docs/api/configuration.md");
const schema = JSON.parse(await readFile(schemaPath, "utf8"));

function display(value) {
  return value === undefined ? "—" : `\`${JSON.stringify(value)}\``;
}

function range(definition) {
  if (definition.minimum === undefined && definition.maximum === undefined) return "—";
  return `\`${String(definition.minimum)}..${String(definition.maximum)}\``;
}

function tableRows(definition, prefix) {
  return Object.entries(definition.properties ?? {}).map(([name, property]) => {
    const resolved = property.$ref ? schema.$defs[property.$ref.replace("#/$defs/", "")] : property;
    return `| \`${prefix}.${name}\` | ${display(resolved.default)} | ${range(resolved)} | ${resolved.description ?? "See the schema constraints."} |`;
  });
}

const profiles = Object.entries(schema.properties.profiles.properties).flatMap(
  ([profileId, reference]) => {
    const profile = schema.$defs[reference.$ref.replace("#/$defs/", "")];
    const objectForm = profile.oneOf.find((entry) => entry.type === "object");
    return Object.keys(objectForm.properties.surfaces.properties).map(
      (surfaceId) => `| \`${profileId}\` | \`${surfaceId}\` | enabled |`,
    );
  },
);

const sections = [
  ["Resource limits", schema.$defs.limits, "limits"],
  ["Command evidence", schema.$defs.commands, "commands"],
  ["Security policy inputs", schema.$defs.security, "security"],
  ["Standards", schema.$defs.standards, "standards"],
  ["Efficiency", schema.$defs.efficiency, "efficiency"],
];

const nestedEfficiency = [
  ...tableRows(schema.$defs.efficiency.properties.budgets, "efficiency.budgets"),
  ...tableRows(schema.$defs.efficiency.properties.componentWeights, "efficiency.componentWeights"),
  ...tableRows(schema.$defs.efficiency.properties.gradeThresholds, "efficiency.gradeThresholds"),
];

function limitRows(definitions, values) {
  return definitions.map(
    ([key, label]) => `| ${label} (\`${key}\`) | ${values[key].toLocaleString("en-US")} |`,
  );
}

const sourceLimitRows = limitRows(
  [
    ["maximumBytes", "UTF-8 source bytes"],
    ["maximumAliases", "YAML aliases"],
    ["maximumDepth", "Nested collections"],
    ["maximumCollectionEntries", "Collection entries"],
    ["maximumNodes", "YAML key and value nodes"],
    ["maximumScalarBytes", "UTF-8 bytes in one decoded scalar"],
    ["maximumIssues", "Reported validation issues"],
  ],
  CONFIGURATION_SOURCE_LIMITS,
);

const valueLimitRows = limitRows(
  [
    ["maximumContainerEntries", "Entries in one decoded container"],
    ["maximumKeyBytes", "UTF-8 bytes in one decoded key"],
    ["maximumStringBytes", "UTF-8 bytes in one decoded string"],
    ["maximumTotalStringBytes", "Cumulative UTF-8 key and string bytes"],
    ["maximumValues", "Decoded JSON values"],
  ],
  CONFIGURATION_VALUE_LIMITS,
);

const text = `<!-- Generated by scripts/generate-configuration-reference.mjs. Do not edit manually. -->

# Repository configuration

Agent Context Linter accepts one versioned repository configuration source named \`.agent-context-lint.yml\`. Public \`@agent-context/core\` owns the decoded-value contracts, schema, defaults, and \`validateAgentContextConfiguration\`; it has no YAML runtime dependency. Private \`@agent-context/syntax\` owns the exact \`yaml@2.9.0\` runtime. Its parser accepts an explicit source string, is deterministic and offline, and never reads files, follows links, executes repository commands, or accesses the network. Its resolver reads the one repository-root source through a bounded, read-only filesystem operation.

The public decoded-value schema is [\`agent-context-lint-config.v1.schema.json\`](../../packages/core/schemas/agent-context-lint-config.v1.schema.json). YAML is decoded with the YAML 1.2 core schema before the same runtime contract is applied.

## Minimal configuration

\`\`\`yaml
version: 1
\`\`\`

Omitted settings receive the defaults below. YAML profile keys use the documented camel-case names; the returned configuration uses canonical D01 profile IDs such as \`codex-cli\`. The returned configuration is deeply frozen. Validation is fail-closed: any malformed value, warning, duplicate key, unknown key, unsupported rule option, or resource-limit breach rejects the entire source; partially defaulted output is never returned.

## Discovery and precedence

\`resolveAgentContextConfiguration(repositoryRoot, options)\` applies exactly three layers, from highest to lowest authority:

1. sparse \`options.cliOverrides\` values;
2. \`.agent-context-lint.yml\` directly inside the explicit repository root;
3. the built-in defaults in this reference.

No parent-directory, home-directory, environment-selected, or user-global configuration is searched in v1. A missing repository file is valid and selects the defaults. A present but malformed, unreadable, oversized, linked, non-regular, or concurrently replaced repository file rejects the complete resolution. An invalid CLI layer also rejects the complete resolution. The resolver never silently discards an invalid higher-authority layer.

The repository-root argument must be an absolute, well-formed Unicode path without NUL bytes. Terminal host separators are removed without changing filesystem-root identity before the selected leaf is inspected, so a separator cannot cause a directory symlink to be dereferenced before it is rejected.

CLI overrides are a sparse JSON object and do not contain \`version\`. Plain nested objects merge recursively, while arrays, booleans, scalars, and \`null\` replace the lower-authority value. This means a profile boolean shorthand replaces that profile object and an \`ignore\` array replaces the repository list. The fully combined value is validated through the same B06 contract and returned deeply frozen. The ordered \`sources\` result records only layers that participated; operational and validation issues identify \`repository\` or \`cli\`, and YAML issues retain exact source locations.

## Profiles and surfaces

Omitted profiles and surfaces are enabled. A profile accepts a boolean shorthand or \`{ enabled, surfaces }\`. A surface can only appear under its owning profile.

| Profile | Surface | Default |
| --- | --- | --- |
${profiles.join("\n")}

## Rules

Rule keys must match \`^ACL[0-9]{3}$\`. A value is a severity shorthand (\`error\`, \`warning\`, \`info\`, or \`off\`) or an object with required \`severity\` and optional integer \`maxTokens\` from 1 through 10,000,000. Explicit \`null\` resets \`maxTokens\` to no rule-specific budget. No other rule option is accepted. At most 512 rule settings are allowed.

\`\`\`yaml
version: 1
rules:
  ACL001: error
  ACL123:
    severity: warning
    maxTokens: 4000
\`\`\`

## Ignore patterns

\`ignore\` is an ordered list of at most 256 unique, non-empty, canonical root-relative POSIX glob strings. Each decoded pattern is limited to 1,024 Unicode code points. Absolute patterns, backslashes, control characters, empty or dot path segments, repeated separators, parent traversal, and duplicates are rejected. Expansion semantics belong to B07 discovery; B06 only validates and preserves this list.

## Settings and defaults

| Setting | Default | Inclusive range | Purpose |
| --- | --- | --- | --- |
${sections.flatMap(([heading, definition, prefix]) => [`| **${heading}** |  |  |  |`, ...tableRows(definition, prefix)]).join("\n")}
${nestedEfficiency.join("\n")}

The only tokenizer value in version 1 is \`estimate\`, and the only score formula is \`1.0.0\`. Component weights are integer percentages whose fully defaulted values must sum to exactly 100. Grade floors are inclusive and must satisfy \`A > B > C > D\`; \`F\` is below \`D\`. A zero token budget permits only a zero observation. Penalty curves, integer rounding, metric normalization, and score-version semantics are published in [Efficiency score specification](efficiency-score-specification.md). These relational constraints are enforced by runtime validation because portable JSON Schema cannot express cross-property sums or ordering. Security flags are inputs to later rules and never grant filesystem or network capability. The standards channel and lockfile are local selections; only explicit standards operations may use the network.

## YAML safety and source limits

| Limit | Maximum |
| --- | ---: |
${sourceLimitRows.join("\n")}

Anchors, aliases, explicit tags, non-string mapping keys, malformed Unicode, YAML warnings, and duplicate keys are rejected. Runtime decoded-value validation separately bounds containers, keys, strings, total string bytes, and total values, and rejects accessors, proxies, cycles, exotic prototypes, sparse arrays, symbols, non-finite numbers, and negative zero without invoking user code.

## Decoded-value runtime limits

| Limit | Maximum |
| --- | ---: |
${valueLimitRows.join("\n")}

The JSON Schema intentionally covers the portable decoded JSON shape and per-field constraints. Aggregate UTF-8 byte and value counts cannot be expressed portably in JSON Schema, while accessors, proxies, cycles, prototypes, sparse arrays, symbols, non-finite numbers, and negative zero are properties of JavaScript runtime values rather than the JSON data model. The runtime validator therefore applies the five limits above and the stricter authority checks before schema-equivalent configuration validation. Exceeding one of these runtime-only limits is a documented rejection, not a schema/runtime compatibility defect.

## Unknown keys and locations

Every structural object is closed. Unknown top-level sections, section fields, profile IDs, surfaces, rule IDs, and rule options are errors. Each YAML-originated issue includes the repository-relative configuration path and a half-open source range with zero-based line, UTF-16 column/offset, and UTF-8 byte offset. Unknown-key diagnostics select the key token rather than its value. Diagnostic paths use dot segments only for safe identifier keys and JSON-quoted bracket segments for dotted, bracketed, or prototype-shaped keys, so a literal key such as \`profiles.codexCli\` cannot collide with nested \`profiles.codexCli\` authority. Decoded-value validation has the same issue paths but no source location unless the caller supplies \`locate\`; callers with distinct key evidence may additionally supply \`locateKey\`.
`;

const prettierOptions = (await resolveConfig(outputPath)) ?? {};
const formattedText = await format(text, { ...prettierOptions, parser: "markdown" });
const mode = process.argv[2] ?? "--check";
if (mode === "--write") {
  await writeFile(outputPath, formattedText, "utf8");
} else if (mode === "--check") {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  if (current !== formattedText) {
    console.error("docs/api/configuration.md is stale; run pnpm config:reference");
    process.exitCode = 1;
  }
} else {
  throw new Error("usage: generate-configuration-reference.mjs --write|--check");
}
