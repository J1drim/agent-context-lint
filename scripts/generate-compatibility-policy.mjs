import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import prettier from "prettier";

import {
  COMPATIBILITY_POLICY,
  COMPATIBILITY_POLICY_VERSION,
  MAX_COMPATIBILITY_CHANGE_ID_BYTES,
  MAX_COMPATIBILITY_SURFACE_ID_BYTES,
  validateCompatibilityPolicy,
} from "../packages/core/dist/compatibility-policy.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const policyPath = path.join(root, "packages/core/policies/compatibility-policy.v1.json");
const documentationPath = path.join(root, "docs/api/compatibility-policy.md");
const mode = process.argv[2];

if (process.argv.length !== 3 || (mode !== "--write" && mode !== "--check")) {
  throw new TypeError("usage: node scripts/generate-compatibility-policy.mjs --write|--check");
}

function words(value) {
  return value.replaceAll("-", " ");
}

function bullets(values) {
  return values.map((value) => `- \`${value}\`: ${words(value)}.`).join("\n\n");
}

function surfaceSection(surface) {
  return `## ${surface.id}

Version authority: **${surface.versionAuthority}**. Release scheme: \`${surface.releaseScheme}\`.

| Minimum | Value |
| --- | ---: |
| Advance notice before a planned removal | ${surface.window.minimumNoticeDays} days |
| Deprecation releases before a planned removal | ${surface.window.minimumDeprecationMinorReleases} minor release(s) |
| Previous-major support after successor GA | ${surface.window.minimumPriorMajorSupportDays} days |
| Published artifact retention | \`${surface.window.publishedArtifactRetention}\` |

### Patch changes

${bullets(surface.changes.patch)}

### Minor changes

${bullets(surface.changes.minor)}

### Major changes

${bullets(surface.changes.major)}

### Migration evidence

Migration evidence is required for: ${surface.migration.requiredFor.map((value) => `\`${value}\``).join(", ")}.

${bullets(surface.migration.evidence)}

### Non-negotiable invariants

${bullets(surface.invariants)}

Owners: ${surface.owners.map((value) => `\`${value}\``).join(", ")}. Required reviewers: ${surface.reviewers.map((value) => `\`${value}\``).join(", ")}.
`;
}

const summaryRows = COMPATIBILITY_POLICY.surfaces
  .map(
    (surface) =>
      `| \`${surface.id}\` | ${surface.window.minimumNoticeDays} days | ${surface.window.minimumDeprecationMinorReleases} | ${surface.window.minimumPriorMajorSupportDays} days | \`${surface.window.publishedArtifactRetention}\` |`,
  )
  .join("\n");

const documentation = `<!-- Generated by scripts/generate-compatibility-policy.mjs. Do not edit manually. -->

# Compatibility and deprecation policy

Policy version: \`${COMPATIBILITY_POLICY_VERSION}\`. Status: **${COMPATIBILITY_POLICY.status}**. Effective date: **${COMPATIBILITY_POLICY.effectiveDate}**.

This is the B10 compatibility authority for the CLI, public library, profile behavior, versioned output schemas, diagnostic baselines, and standards knowledge packs. The machine-readable authority is [\`compatibility-policy.v1.json\`](../../packages/core/policies/compatibility-policy.v1.json). \`validateCompatibilityPolicy\` verifies an untrusted copy against the exact published authority, and \`classifyCompatibilityChange\` fails closed for unknown surfaces or changes.

Both public functions are hostile-input boundaries and return deeply frozen results. Classification accepts only bounded ASCII identifier segments: at most ${MAX_COMPATIBILITY_SURFACE_ID_BYTES} bytes for a surface and ${MAX_COMPATIBILITY_CHANGE_ID_BYTES} bytes for a change. Rejections use stable non-reflective text, so control characters, bidirectional controls, huge values, or secret-bearing input cannot be copied into logs by the classifier.

The policy applies to intentional changes and bug fixes whose observable result differs from the published contract. Calling a change a correction does not make it compatible. If classification is disputed, use the higher-risk class until the required owners agree. Notice and support windows are minimums, not a promise that unsafe, compromised, revoked, or upstream-impossible behavior will remain active.

## Release rules

- Stable public APIs start at major version 1. Patch releases preserve accepted inputs, outputs, documented behavior, and security posture. Backward-compatible additions and deprecations use minor releases. Incompatible changes use major releases.
- \`@agent-context/core\` and \`@agent-context/lint\` are versioned together until a superseding ADR and tested compatibility matrix say otherwise.
- The \`1.0.0\` release is stable. Any future pre-release line must publish separate release notes and migration fixtures before distribution.
- A published version is immutable. An accidental break is withdrawn or superseded, affected versions are documented, compatibility is restored promptly, and the artifact is never rewritten.
- A planned removal must satisfy both its day count and its minor-release count. The deprecated path remains functional and tested throughout that window. Removal then requires a major release.
- Previous-major support begins when the successor major reaches GA. During the stated period, high and critical security fixes are backported when technically safe; users receive an upgrade path and explicit end date. Immutable schemas, evidence snapshots, baselines, and pack identities remain addressable where their retention is \`indefinite\`.
- Maintenance support and artifact availability are separate. Support may end after the documented window, but every published public npm package version remains downloadable indefinitely. End of life uses npm deprecation, which preserves dependent builds, rather than project-initiated unpublishing.
- Availability can be lost only through a registry-enforced, legal, privacy, or security takedown outside project control: ${COMPATIBILITY_POLICY.semver.externalTakedownBehavior}

| Surface | Notice | Deprecated minor releases | Previous-major support | Artifact retention |
| --- | ---: | ---: | ---: | --- |
${summaryRows}

## Schema identity and migration

Every product schema declares its exact dialect and immutable \`$id\`; every instance carries the family-specific \`recordKind\` and semantic \`schemaVersion\`. An identifier is never reassigned to a changed shape or meaning. Minor additions are accepted only where old producers remain valid and every supported consumer has documented unknown-field/value behavior. Closed older validators continue to reject newer producers; a compatibility classification never bypasses exact runtime validation.

A supported old version has an explicit schema/export, validator, frozen positive/negative/boundary fixtures, and a pure migration. Migration validates the source, writes a separate destination atomically, validates it completely, and preserves the original. Down-conversion is offered only when reviewed as lossless or when documented loss is explicit. Persisted baselines and reports are never edited in place.

## Profile drift and uncertainty

A changed vendor page, client release, or observation creates a review trigger and a new dated \`specSnapshotId\`; it does not rewrite old evidence or prove runtime behavior. Profile changes record source URL, retrieval date, client/upstream version, revision or digest, observed-versus-documented differences, and assumptions. Undocumented, model-selected, UI-only, hosted, or version-dependent behavior remains \`conditional\`, \`unknown\`, or \`contradiction\` until evidence supports a narrower state.

If upstream removes behavior before the ordinary profile window can finish, the project retains the historical snapshot, marks current support accurately, and uses the emergency record below if retaining the old behavior is impossible or unsafe. It does not invent an alias, precedence rule, or activation result to simulate compatibility.

## Baseline comparability

Diagnostic baselines compare only matching schema and fingerprint-method versions unless an explicit migrator produces a separately validated baseline. A comparability-affecting change requires a reviewed migration; no conversion can manufacture comparability.

## Knowledge-pack trust and rollback

H01 pack content versions are exact SemVer values bound to canonical RFC 8785 bytes, length, and SHA-256 digest; bundled pack \`schemaVersion\`, \`adapterVersion\`, \`rulesetVersion\`, and \`minEngineVersion\` are separate exact SemVer identities. Packs are data only. Discovery, parsing, precedence, imports, glob semantics, executable rule logic, or trust behavior require an engine release. H01 parsing alone never authorizes activation: H02 owns the exact TUF trust design and H03 must verify metadata, target path/length/digest, channel, schema version, and minimum engine before parsing. Stable and preview remain separate delegated roles.

The same version with different bytes, expired or inconsistent metadata, rollback/freeze/mix-and-match evidence, wrong channel, unsupported engine, revoked target, or unknown root fails closed. CI never silently updates. Rollback restores only a previously verified, compatible, non-revoked lock. A yank stops new selection without rewriting history; a security revocation blocks activation but retains the digest and incident identity for audit. Registry outage leaves verified locked offline scanning available and reports freshness as unknown rather than claiming global currency.

## Emergency security exception

Only these triggers may shorten notice:

${bullets(COMPATIBILITY_POLICY.emergency.allowedTriggers)}

Break-glass access expires within ${COMPATIBILITY_POLICY.emergency.maximumBreakGlassHours} hours. It requires ${COMPATIBILITY_POLICY.emergency.requiredApprovals.map((value) => `\`${value}\``).join(", ")}, review within ${COMPATIBILITY_POLICY.emergency.reviewWithinHours} hours, and a retrospective within ${COMPATIBILITY_POLICY.emergency.retrospectiveWithinBusinessDays} business days. The record must contain:

${bullets(COMPATIBILITY_POLICY.emergency.recordFields)}

The exception can shorten notice; it cannot avoid the SemVer impact, migration evidence, immutable artifact, user communication, or rollback requirement. It can never waive:

${bullets(COMPATIBILITY_POLICY.emergency.nonWaivable)}

## Surface matrices

${COMPATIBILITY_POLICY.surfaces.map(surfaceSection).join("\n")}

## Primary standards basis

Reviewed 2026-08-02:

- [Semantic Versioning 2.0.0](https://semver.org/) defines the public API, immutable released versions, patch/minor/major meanings, and a minor release for deprecation before later major removal.
- [JSON Schema: declaring a schema](https://json-schema.org/understanding-json-schema/basics) recommends an explicit dialect \`$schema\` and unique \`$id\`.
- [npm's Unpublish Policy](https://docs.npmjs.com/policies/unpublish/) explains that registry data is immutable, an unpublished name/version cannot be reused, and deprecation preserves availability for dependent builds. The [npm deprecation guidance](https://docs.npmjs.com/deprecating-and-undeprecating-packages-or-package-versions/) recommends deprecation instead of unpublishing.
- [The Update Framework 1.0.35 specification](https://theupdateframework.github.io/specification/v1.0.35/) defines threshold trust and defenses against rollback, freeze, mix-and-match, and wrong-target attacks. H02 owns the exact implementation profile and any later TUF-version adoption; this policy does not silently select one.
`;

const prettierConfig = (await prettier.resolveConfig(documentationPath)) ?? {};
const expectedDocumentation = await prettier.format(documentation, {
  ...prettierConfig,
  filepath: documentationPath,
});
const expectedPolicy = await prettier.format(JSON.stringify(COMPATIBILITY_POLICY), {
  ...prettierConfig,
  filepath: policyPath,
});
const parsedPolicy = JSON.parse(expectedPolicy);
if (!validateCompatibilityPolicy(parsedPolicy).ok) {
  throw new TypeError("generated compatibility policy does not validate");
}

if (mode === "--write") {
  await writeFile(policyPath, expectedPolicy, "utf8");
  await writeFile(documentationPath, expectedDocumentation, "utf8");
  process.stdout.write("Generated compatibility policy JSON and documentation.\n");
} else {
  const [actualPolicy, actualDocumentation] = await Promise.all([
    readFile(policyPath, "utf8").catch(() => ""),
    readFile(documentationPath, "utf8").catch(() => ""),
  ]);
  if (actualPolicy !== expectedPolicy || actualDocumentation !== expectedDocumentation) {
    throw new TypeError(
      "compatibility policy artifacts are missing or stale; run pnpm compatibility:reference",
    );
  }
  process.stdout.write("Compatibility policy JSON and documentation are current.\n");
}
